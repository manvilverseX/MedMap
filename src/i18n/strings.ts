export function t(
  key: StringKey,
  lang: LangCode = "en",
  cachedOverrides?: Record<string, string> | null,
  vars?: Record<string, string | number>
): string {
  let text: string | undefined;

  if (lang === "kn" && KN_STRINGS[key]) {
    text = KN_STRINGS[key];
  } else if (lang === "hi" && HI_STRINGS[key]) {
    text = HI_STRINGS[key];
  } else if (cachedOverrides && cachedOverrides[key]) {
    text = cachedOverrides[key];
  } else if (lang !== "en") {
    const cached = getCachedStrings(lang);
    if (cached && cached[key]) {
      text = cached[key];
    }
  }

  if (!text) {
    text = EN_STRINGS[key] ?? (key as string);
  }

  return vars ? interpolate(text, vars) : text;
}
