// ── Cache helpers ──────────────────────────────────────────────────────────────

const CACHE_PREFIX = "medmap_i18n_";

function cacheKey(lang: LangCode): string {
  return `${CACHE_PREFIX}${lang}`;
}

export function getCachedStrings(lang: LangCode): Record<string, string> | null {
  if (lang === "en") return null;
  try {
    const raw = sessionStorage.getItem(cacheKey(lang));
    if (!raw) return null;
    return JSON.parse(raw) as Record<string, string>;
  } catch {
    return null;
  }
}

export function setCachedStrings(lang: LangCode, strings: Record<string, string>): void {
  try {
    sessionStorage.setItem(cacheKey(lang), JSON.stringify(strings));
  } catch {
    // Storage quota exceeded – ignore
  }
}

// ── Interpolation ─────────────────────────────────────────────────────────────

/**
 * Replace `{{key}}` or `{key}` placeholders in a string.
 * Tolerant: never leaves raw {{key}}, {key}, or trailing separators if variables are missing.
 */
export function interpolate(
  template: string,
  vars?: Record<string, string | number | undefined | null>
): string {
  if (!template) return "";
  if (!vars) {
    return template.replace(/\{\{?\w+\}?\}|~?\{\{?\w+\}?\}|\/?\s*\{\{?\w+\}?\}|of\s*~?\{\{?\w+\}?\}/g, "").trim();
  }
  let result = template
    .replace(/\{\{(\w+)\}\}/g, (_, key) => {
      const v = vars[key];
      return v !== undefined && v !== null && v !== "" ? String(v) : "";
    })
    .replace(/\{(\w+)\}/g, (_, key) => {
      const v = vars[key];
      return v !== undefined && v !== null && v !== "" ? String(v) : "";
    });

  // Clean up any trailing / dangling separators caused by missing variables (e.g. "/ लगभग " or "of ~")
  result = result
    .replace(/\/\s*लगभग\s*$/g, "")
    .replace(/\/\s*ಸುಮಾರು\s*$/g, "")
    .replace(/of\s*~\s*$/g, "")
    .replace(/\/\s*~?\s*$/g, "")
    .trim();

  return result;
}

